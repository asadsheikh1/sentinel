"""Generate docs/rbac.md from the code: role map, key scopes, and every route's access rule.

``route_table`` is also what the "every route declares access" test uses, so
the doc, the test and the running app all read the same source.
"""

import sys
from collections.abc import Callable, Iterator
from dataclasses import dataclass
from pathlib import Path

from fastapi import FastAPI
from fastapi.dependencies.models import Dependant
from fastapi.routing import APIRoute
from starlette.routing import BaseRoute

from sentinel.api.security import Access, route_access
from sentinel.auth.permissions import ROLE_PERMISSIONS, KeyScope, Permission
from sentinel.db.models import UserRole


@dataclass(frozen=True)
class RouteInfo:
    method: str
    path: str
    access: list[Access]

    def allowed_roles(self) -> str:
        if len(self.access) != 1:
            return "—"
        a = self.access[0]
        if a.kind == "public":
            return "everyone"
        if a.kind == "authenticated":
            return "all roles"
        if a.kind == "scope":
            return "API keys only"
        if a.kind == "internal":
            return "SENTINEL's reverse proxy only"
        perm = Permission(str(a.value))
        return ", ".join(r.value for r in UserRole if perm in ROLE_PERMISSIONS[r])


def _calls(dep: Dependant) -> Iterator[Callable[..., object]]:
    for sub in dep.dependencies:
        if sub.call is not None:
            yield sub.call
        yield from _calls(sub)


def _api_routes(routes: list[BaseRoute]) -> Iterator[APIRoute]:
    for route in routes:
        if isinstance(route, APIRoute):
            yield route
        elif (inner := getattr(route, "original_router", None)) is not None:
            # FastAPI >= 0.16x keeps included routers wrapped. Our routers carry
            # their full prefix, and the OpenAPI cross-check test guards this walk.
            yield from _api_routes(inner.routes)
        # else: OpenAPI/docs routes provided by the framework (disabled in prod)


def route_table(app: FastAPI) -> list[RouteInfo]:
    out: list[RouteInfo] = []
    for route in _api_routes(app.routes):
        access = route_access(list(_calls(route.dependant)))
        for method in sorted(route.methods or ()):
            out.append(RouteInfo(method, route.path, access))
    return sorted(out, key=lambda r: (r.path, r.method))


def render(app: FastAPI) -> str:
    roles = list(UserRole)
    lines = [
        "# Access control reference (generated)",
        "",
        "> Generated by `make rbac-docs` from `backend/src/sentinel/auth/permissions.py` and the "
        "route declarations. **Do not edit by hand.** Rationale: "
        "[2-architecture/6-security.md](2-architecture/6-security.md).",
        "",
        "## Roles → permissions",
        "",
        "| Permission | " + " | ".join(r.value for r in roles) + " |",
        "|---|" + ":-:|" * len(roles),
    ]
    for perm in Permission:
        marks = " | ".join("✅" if perm in ROLE_PERMISSIONS[r] else "" for r in roles)
        lines.append(f"| `{perm.value}` | {marks} |")
    lines += [
        "",
        "## API-key scopes",
        "",
        "Machine keys (`X-Sentinel-Key`) carry scopes, never user permissions.",
        "",
    ]
    lines += [f"- `{s.value}`" for s in KeyScope]
    lines += [
        "",
        "## Routes",
        "",
        "| Method | Path | Requires | Allowed |",
        "|---|---|---|---|",
    ]
    for r in route_table(app):
        requires = ", ".join(a.describe() for a in r.access) or "**MISSING**"
        lines.append(f"| {r.method} | `{r.path}` | {requires} | {r.allowed_roles()} |")
    return "\n".join(lines) + "\n"


def write_or_check(app: FastAPI, output: str, *, check: bool) -> int:
    path = Path(output)
    content = render(app)
    if check:
        if not path.exists() or path.read_text() != content:
            print(f"{path} is out of date. Run `make rbac-docs`.", file=sys.stderr)
            return 1
        print(f"{path} is up to date.")
        return 0
    path.write_text(content)
    print(f"Wrote {path}")
    return 0
