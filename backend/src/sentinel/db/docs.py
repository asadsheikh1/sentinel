"""Generate ``docs/database.md`` (column-level reference) from the SQLAlchemy models.

Deterministic and offline: no database needed. CI runs it with ``--check`` so
the committed file can't drift from the models.
"""

import sys
from pathlib import Path

from sqlalchemy import CheckConstraint, Column, Index, Table, UniqueConstraint
from sqlalchemy.dialects import postgresql

import sentinel.db.models  # noqa: F401  (registers tables)
from sentinel.db.base import Base

_DIALECT = postgresql.dialect()  # type: ignore[no-untyped-call]

HEADER = """# Database reference (generated)

> Generated by `make db-docs` from `backend/src/sentinel/db/models`. **Do not edit by hand.**
> Design rationale: [2-architecture/4-database.md](2-architecture/4-database.md).

"""


def _type(col: Column[object]) -> str:
    return str(col.type.compile(dialect=_DIALECT))


def _default(col: Column[object]) -> str:
    if col.server_default is not None:
        arg = getattr(col.server_default, "arg", None)
        return f"`{getattr(arg, 'text', arg)}`"
    if col.default is not None:
        fn = getattr(col.default, "arg", None)
        return f"app: `{getattr(fn, '__name__', fn)}()`" if callable(fn) else f"app: `{fn}`"
    return ""


def _fk(col: Column[object]) -> str:
    parts = []
    for fk in col.foreign_keys:
        on_delete = f" ON DELETE {fk.ondelete}" if fk.ondelete else ""
        parts.append(f"→ `{fk.target_fullname}`{on_delete}")
    return ", ".join(parts)


def _where(index: Index) -> str:
    clause = index.dialect_options["postgresql"].get("where")
    return "" if clause is None else str(clause)


def _escape(value: str) -> str:
    return value.replace("|", "\\|")


def render_table(table: Table) -> str:
    out = [f"## `{table.name}`\n"]
    doc = (table.comment or "").strip()
    if doc:
        out.append(doc + "\n")
    out.append("| Column | Type | Null | Default | Key / reference |")
    out.append("|---|---|---|---|---|")
    unique_cols = {
        c.columns.keys()[0]
        for c in table.constraints
        if isinstance(c, UniqueConstraint) and len(c.columns) == 1
    }
    for col in table.columns:
        key = []
        if col.primary_key:
            key.append("PK")
        if col.unique or col.name in unique_cols:
            key.append("unique")
        if fk := _fk(col):
            key.append(fk)
        out.append(
            f"| `{col.name}` | {_escape(_type(col))} | {'yes' if col.nullable else 'no'} "
            f"| {_escape(_default(col))} | {_escape(' '.join(key))} |"
        )

    checks = sorted(
        (str(c.name), str(c.sqltext)) for c in table.constraints if isinstance(c, CheckConstraint)
    )
    indexes = sorted(
        (
            str(i.name),
            ", ".join(str(e) for e in i.expressions),
            _where(i),
        )
        for i in table.indexes
        if isinstance(i, Index)
    )
    if checks:
        out.append("\n**Checks:** " + "; ".join(f"`{_escape(sql)}`" for _, sql in checks))
    if indexes:
        out.append(
            "\n**Indexes:** "
            + "; ".join(
                f"`{name}` ({_escape(cols)}{' WHERE ' + _escape(where) if where else ''})"
                for name, cols, where in indexes
            )
        )
    return "\n".join(out) + "\n"


def render() -> str:
    tables = sorted(Base.metadata.tables.values(), key=lambda t: t.name)
    body = "\n".join(render_table(t) for t in tables)
    return HEADER + body


def write_or_check(output: str, *, check: bool) -> int:
    path = Path(output)
    content = render()
    if check:
        if not path.exists() or path.read_text() != content:
            print(f"{path} is out of date. Run `make db-docs`.", file=sys.stderr)
            return 1
        print(f"{path} is up to date.")
        return 0
    path.write_text(content)
    print(f"Wrote {path}")
    return 0
